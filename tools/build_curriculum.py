d=json.load(open(sys.argv[1],encoding='utf-8'))
songs={}
def slug(s): return re.sub(r'[^a-z]+','-',s.lower()).strip('-')[:28].strip('-')
out=[]
for o in d:
  t=o['title']; t=re.sub(r'\s+References?:.*$','',t); t=re.sub(r'\s+(III|IV)$','',t).strip() if o['level']>=3 else t
  t=t.replace('Plight to Egypt','Flight to Egypt')
  text=[]
  for p in o['text']:
    p=re.sub(r'^Objective:.*?(?=Introduction|The Lesson|$)','',p).strip()
    p=re.sub(r'^(Introduction|The Lesson)\s*:?\s*','',p).strip()
    if not p or re.match(r'^(Song|Hymn|Meaning|Ethiopian Orthodox)',p) or re.search(r'Color the|Practice the following|Sing the following',p): continue
    p=re.sub(r'Ethiopian Orthodox Tewahedo Church \d+.*$','',p).strip()
    if p: text.append(p)
  sid=None
  if o['song'] and o['song']['lines']:
    first=re.sub(r'\(\d\)|/\d/','',o['song']['lines'][0]).strip()
    sid=slug(first)
    songs.setdefault(sid,{'lines':o['song']['lines'],'meaning':re.sub(r'\s*\d*\s*Ethiopian Orthodox.*$','',o['song']['meaning']).strip(),'fidel':None})
  e={'id':o['id'],'level':o['level'],'month':o['month'],'week':o['week'],'title':t,'objective':o['objective'],'refs':o['refs'],'verse':o['verse'],'song':sid,'text':text}
  if o['id'] in BUILT: e['built']=BUILT[o['id']]
  out.append(e)
hdr='/* All 187 lessons from the four Sunday school PDFs (compiled by Kesis Solomon Mulugeta), in church-year order.\n   Generated by tools/build_curriculum.py. "built" marks lessons that have an interactive version. */\n'
open('data/curriculum.js','w',encoding='utf-8').write(hdr+'window.BK_CURR='+json.dumps(out,ensure_ascii=False,indent=0)+';\n')
open('data/songs.js','w',encoding='utf-8').write('/* Mezmur (songs) from the lessons. Lyrics are in Latin letters as printed; fidel is to be written by a native speaker.\n   A recording goes in audio/songs/<id>.mp3 and its id in data/audio.js. */\nwindow.BK_SONGS='+json.dumps(songs,ensure_ascii=False,indent=1)+';\n')
